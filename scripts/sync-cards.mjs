// Regenerates app/data/cards.generated.ts from the Rough Day game repo: the power-up catalogue
// (src/game/powerups.js) and the flat help pictures used as card art (src/ui/helpPictures.js).
//
//   node scripts/sync-cards.mjs [path-to-game-repo]
//
// Card art is never AI generated: it is the same SVG the game shows on its own cards.
import { writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { resolve } from 'node:path'

const game = resolve(process.argv[2] ?? process.env.GAME_REPO ?? '../mini-golf-test')
const { POWERUPS } = await import(pathToFileURL(`${game}/src/game/powerups.js`).href)
const { helpPicture } = await import(pathToFileURL(`${game}/src/ui/helpPictures.js`).href)

const art = (id) =>
  helpPicture(`power:${id}`)
    .replace(/\s*role="img" aria-label="[^"]*"/, ' aria-hidden="true"')
    .replace(/\n\s*/g, '')
    .trim()

const cards = Object.values(POWERUPS).map((p) => ({
  id: p.id,
  name: p.name,
  icon: p.icon,
  active: p.active,
  levels: p.levels.map((l) => l.desc),
  art: art(p.id),
}))

const missing = cards.filter((c) => !c.art).map((c) => c.id)
if (missing.length) throw new Error(`No card art for: ${missing.join(', ')}`)

const body = `// Generated by scripts/sync-cards.mjs from the game repo. Do not edit by hand.
export interface PowerCard {
  id: string
  name: string
  icon: string
  /** true = tap a button during a putt, false = always on */
  active: boolean
  /** What each level does, level I first. */
  levels: string[]
  /** Inline SVG, the same flat picture the game uses as card art. */
  art: string
}

export const powerCards: PowerCard[] = ${JSON.stringify(cards, null, 2)}
`
writeFileSync(new URL('../app/data/cards.generated.ts', import.meta.url), body)
console.log(`Wrote ${cards.length} cards from ${game}`)
